"""
Build a synthetic single-turn dataset from the chat exports.

For every conversation window produced by chat_to_json.convert_chat_to_training_data:
    1. ask the local Bielik model to write ONE user message that stands in for
       the whole user side of the window,
    2. squash all assistant messages of the window into one reply (newline-joined),
    3. keep the original system prompt.

Result per example:
    [system, user (generated by Bielik), assistant (squashed replies)]

Output uses the same {"conversations": [...]} JSON format as chat_to_json.py,
so training.py can consume it directly.

Run from the repository root:
    uv run python parsing/synthetic_data_generation.py
"""

import json  # noqa: I001

# Unsloth must be imported before transformers/torch to apply its patches.
from unsloth import FastLanguageModel
import torch

from parsing.chat_to_json import convert_chat_to_training_data

# ========================================
# CONFIG
# ========================================

MODEL_NAME = "speakleash/Bielik-4.5B-v3.0-Instruct"
MODEL_NAME = "speakleash/Bielik-Minitron-7B-v3.0-Instruct"
OUTPUT_PATH = "./data/synthetic_chat_ania_v4.json"

# Source conversations (same settings as chat_to_json.py).
START_CONVERSATION_PROMPTS = ["Hej, co tam?", "Siema!", "Co słychać?"]
GAP_HOURS = 2

# Generation.
MAX_SEQ_LENGTH = 2048
MAX_NEW_TOKENS = 200
TEMPERATURE = 0.7
TOP_P = 0.9
BATCH_SIZE = 8

USER_LABEL = "user"
ASSISTANT_LABEL = "assistant"

GENERATION_PROMPT = """Jesteś generatorem syntetycznych pytań do zbioru treningowego modelu konwersacyjnego. Stosujesz metodę Reverse Instructions: na podstawie autentycznej odpowiedzi człowieka odtwarzasz pytanie, które mogło ją wywołać.

### Zadanie
Otrzymasz fragment prywatnej rozmowy dwóch wieloletnich znajomych. Twoim zadaniem jest wygenerowanie JEDNEGO naturalnego pytania, na które sensowną odpowiedzią byłayby wiadomości oznaczone rolą "assistant".

Wiadomości "assistant" są autentycznymi wypowiedziami człowieka, a nie tekstami generowanymi przez AI.

### Zasady
1. Przeczytaj cały fragment, rozpoznaj temat rozmowy i jej kontekst.
2. Jako docelowa odpowiedź potraktuj wszystkie odpowiedzi assistant, lub ostatnią, w zaleznościod tego co ma więcej sensu.
3. Wygeneruj pytanie, które znajomy mógłby naturalnie zadać bezpośrednio przed tą odpowiedzią.
4. Pytanie musi pasować semantycznie do odpowiedzi i logicznie wynikać z wcześniejszego kontekstu.
5. Nie kopiuj automatycznie poprzedniej wiadomości "user". Możesz ją sparafrazować, jeżeli stanowi dobre pytanie.
6. Nie umieszczaj w pytaniu informacji, które pojawiają się dopiero w docelowej odpowiedzi, chyba że wynikają również z wcześniejszego kontekstu.
7. Nie dodawaj nowych wydarzeń, osób, faktów ani nieznanych szczegółów.
8. Jeżeli odpowiedź jest urwana, ironiczna lub niejednoznaczna, preferuj krótkie, ogólne pytanie zamiast rozbudowanej interpretacji.
9. Nie zmieniaj ani nie generuj odpowiedzi "assistant". Masz wygenerować wyłącznie pytanie.
10. Jeśli nie da się stworzyć sensownego pytania, zwróć null.

### Przykłady

Przykład 1:
Kontekst:
user: "No to widzisz nawet nie wiedziałam\nNie? Stracisz znajomych w ten sposób\nBo czekaj"

Docelowa odpowiedź:
assistant: "Przełączyłem się na inny numer bo w sumie\nCzemu nie.\nNo ale dopiero przed minutą zrobiłem także luz"

Wynik:
"To co ty właściwie zrobiłeś z Twoim poprzednim numerem telefonu?"

Przykład 2:
Kontekst:
user: "Nie widzisz jak piszę na stary numer?\nXD"

Docelowa odpowiedź:
assistant: "No nie widzę, nie, racja, ale przełączę się z powrotem kiedyś\nZresztą do mnie i tak nikt nie pisze :D"

Wynik:
"To w ogóle nie widzisz jak do ciebie piszę? XD"

### Format wyniku
Zwróć wyłącznie poprawnie wygenerowane pytanie lub "NULL". ZADNYCH WYJAŚNIEŃ ANI KOMENTARZY. Nie dodawaj żadnych dodatkowych znaków ani spacji. Nie używaj cudzysłowów ani innych znaków interpunkcyjnych wokół pytania. Nie zmieniaj wielkości liter w pytaniu.

Nie dodawaj wyjaśnień, ocen, komentarzy ani bloków Markdown.

### Fragment rozmowy
{conversation}"""


# ========================================
# HELPERS
# ========================================

def squash_assistant_messages(conversation):
    return "\n".join(m["content"] for m in conversation if m["role"] == "assistant")


def build_prompt(conversation, squashed_reply):
    transcript = "\n".join(
        f"{USER_LABEL if m['role'] == 'user' else ASSISTANT_LABEL}: {m['content']}"
        for m in conversation
        if m["role"] != "system"
    )
    return GENERATION_PROMPT.format(conversation=transcript, reply=squashed_reply)


def clean_generated_message(text):
    """Strip an echoed label and wrapping quotes the model sometimes adds."""
    text = text.strip()
    if text.upper().startswith(USER_LABEL + ":"):
        text = text[len(USER_LABEL) + 1:].strip()
    if len(text) >= 2 and text[0] == text[-1] and text[0] in "\"'„”":
        text = text[1:-1].strip()
    if text.startswith("„") and text.endswith("”"):
        text = text[1:-1].strip()
    return text


def load_model():
    model, tokenizer = FastLanguageModel.from_pretrained(
        model_name=MODEL_NAME,
        max_seq_length=MAX_SEQ_LENGTH,
        dtype=None,
        load_in_4bit=True,
    )
    FastLanguageModel.for_inference(model)
    # Decoder-only models need left padding for batched generation.
    tokenizer.padding_side = "left"
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    return model, tokenizer


@torch.no_grad()
def generate(model, tokenizer, prompts):
    texts = [
        tokenizer.apply_chat_template(
            [{"role": "user", "content": prompt}],
            tokenize=False,
            add_generation_prompt=True,
        )
        for prompt in prompts
    ]
    inputs = tokenizer(texts, return_tensors="pt", padding=True, add_special_tokens=False).to(model.device)
    output = model.generate(
        **inputs,
        max_new_tokens=MAX_NEW_TOKENS,
        do_sample=True,
        temperature=TEMPERATURE,
        top_p=TOP_P,
        pad_token_id=tokenizer.pad_token_id,
    )
    new_tokens = output[:, inputs["input_ids"].shape[1]:]
    return tokenizer.batch_decode(new_tokens, skip_special_tokens=True)


# ========================================
# MAIN
# ========================================

def generate_synthetic_chat_data(chat_files, rolling_window_length, speaker_names, speaker_real_name,
                                 speaker_characteristics, output_path, seed=2137):
    torch.manual_seed(seed)

    conversations = convert_chat_to_training_data(
        file_names=chat_files,
        speaker_names=speaker_names,
        start_conversation_prompts=START_CONVERSATION_PROMPTS,
        speaker_real_name=speaker_real_name,
        speaker_characteristics=speaker_characteristics,
        output_path=None,
        gap_hours=GAP_HOURS,
        max_turns=rolling_window_length,
        seed=seed,
    )
    print(f"Loaded {len(conversations)} conversations")

    model, tokenizer = load_model()

    synthetic, skipped = [], 0
    for start in range(0, len(conversations), BATCH_SIZE):
        batch = conversations[start:start + BATCH_SIZE]
        replies = [squash_assistant_messages(conv) for conv in batch]
        prompts = [build_prompt(conv, reply) for conv, reply in zip(batch, replies)]

        for conv, reply, generated in zip(batch, replies, generate(model, tokenizer, prompts)):
            user_message = clean_generated_message(generated)
            print(f"Generated user message: {user_message}")
            if not user_message:
                skipped += 1
                continue
            synthetic.append([
                conv[0],  # original system prompt
                {"role": "user", "content": user_message},
                {"role": "assistant", "content": reply},
            ])

        print(f"{min(start + BATCH_SIZE, len(conversations))}/{len(conversations)} processed")

    with open(output_path, "w", encoding="utf-8") as f:
        json.dump([{"conversations": conv} for conv in synthetic], f, ensure_ascii=False, indent=2)

    print(f"{len(synthetic)} conversations written to {output_path} ({skipped} skipped: empty generation)")


if __name__ == "__main__":
    generate_synthetic_chat_data(
        chat_files=["./data/asia_chat_1.txt", "./data/asia_chat_2.txt", "./data/asia_chat_3.txt"],
        rolling_window_length=6,
        speaker_names=["Asia", "anierhej"],
        speaker_real_name="Ania",
        speaker_characteristics="35 letnią programistką, rozmawiającą ze swoją koleżanką",
        output_path="./data/synthetic_chat_ania.json"
    )
